-- Add a stable global inbox key and serialize inserts for each recipient.
-- The encrypted per-direction seq remains the only delivery-gap/order signal.

alter table public.messages
  add column message_id bigint generated always as identity;

alter table public.messages
  add constraint messages_pkey primary key (message_id);

-- Supports recipient-scoped keyset pagination without scanning old inbox rows.
create index messages_recipient_message_id_idx
  on public.messages (recipient_id, message_id);

create or replace function public.submit_message(
  p_payload jsonb,
  p_recipient_id uuid default null,
  p_invitation_id text default null
)
returns timestamptz
language plpgsql
security definer
set search_path = pg_catalog, public, extensions
as $function$
declare
  v_sender_id uuid := auth.uid();
  v_recipient_id uuid;
  v_invitation_owner_id uuid;
  v_created_at timestamptz;
  v_user_a uuid;
  v_user_b uuid;
begin
  if v_sender_id is null then
    raise exception 'Authentication required' using errcode = '28000';
  end if;

  if p_payload is null or jsonb_typeof(p_payload) <> 'object' then
    raise exception 'Invalid message payload' using errcode = '22023';
  end if;

  if (p_invitation_id is null) = (p_recipient_id is null) then
    raise exception 'Specify exactly one message route' using errcode = '22023';
  end if;

  if p_invitation_id is not null then
    if length(p_invitation_id) <> 43
       or p_invitation_id !~ '^[A-Za-z0-9_-]{43}$' then
      raise exception 'Invalid invitation' using errcode = '22023';
    end if;

    delete from public.invitations
      where token_hash = extensions.digest(convert_to(p_invitation_id, 'UTF8'), 'sha256')
      returning owner_id into v_invitation_owner_id;

    if v_invitation_owner_id is null then
      raise exception 'Invitation is invalid or already used' using errcode = 'P0001';
    end if;

    if v_invitation_owner_id = v_sender_id then
      raise exception 'Cannot redeem your own invitation' using errcode = '22023';
    end if;

    v_recipient_id := v_invitation_owner_id;
    v_user_a := least(v_sender_id, v_recipient_id);
    v_user_b := greatest(v_sender_id, v_recipient_id);

    insert into public.links (user_a, user_b)
    values (v_user_a, v_user_b)
    on conflict (user_a, user_b) do nothing;
  else
    v_recipient_id := p_recipient_id;

    if v_recipient_id = v_sender_id then
      raise exception 'Cannot message yourself' using errcode = '22023';
    end if;

    v_user_a := least(v_sender_id, v_recipient_id);
    v_user_b := greatest(v_sender_id, v_recipient_id);

    if not exists (
      select 1
      from public.links l
      where l.user_a = v_user_a
        and l.user_b = v_user_b
    ) then
      raise exception 'Recipient is not a contact' using errcode = '42501';
    end if;
  end if;

  -- Serialize every insert into this recipient's inbox. The lock is held
  -- until the surrounding RPC transaction commits or rolls back.
  perform 1
  from auth.users
  where id = v_recipient_id
  for update;

  if not found then
    raise exception 'Recipient account does not exist' using errcode = '22023';
  end if;

  -- message_id is generated by the identity column during this INSERT.
  -- clock_timestamp() is evaluated after the recipient lock was acquired;
  -- unlike now(), it is not the transaction-start timestamp.
  insert into public.messages (sender_id, recipient_id, payload, created_at)
  values (v_sender_id, v_recipient_id, p_payload, clock_timestamp())
  returning created_at into v_created_at;

  return v_created_at;
end;
$function$;

revoke all on function public.submit_message(jsonb, uuid, text) from public, anon;
grant execute on function public.submit_message(jsonb, uuid, text) to authenticated;

comment on column public.messages.message_id is
  'Globally unique inbox row identifier. Used for recipient-scoped incremental pagination; encrypted per-direction seq remains the delivery-order and gap signal.';

comment on table public.messages is
  'Durable recipient inbox. message_id is the global unique pagination key; created_at is the server insertion timestamp; encrypted per-direction seq defines message order and deduplication. Inserts notify private inbox topics through Broadcast.';

comment on function public.submit_message(jsonb, uuid, text) is
  'Atomically redeems an invitation or validates an existing link, serializes inserts by locking the recipient auth.users row, inserts the inbox row with a global message_id and clock_timestamp created_at, and broadcasts it to the recipient inbox topic.';
